def 读(text):
    with tempfile.TemporaryDirectory() as d:
        p = os.path.join(d, 'TODO.md')
        open(p, 'w', encoding='utf-8').write(text)
        return 板.读TODO(p), 板.标题名(p)


def 查(名, 过, 细=''):
    print(('✅ ' if 过 else '❌ ') + 名 + ('' if 过 else '  ' + str(细)))
    if not 过:
        错.append(名)


