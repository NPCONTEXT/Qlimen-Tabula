#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""估时对账的离线测试（11-04 卷二 7.2）：每条用一个临时数据目录（BAN_DATA）、假的开关记录，不碰正在用的看板数据。
跑法：/usr/bin/python3 工具/测对账.py（全过退出码 0）"""
import json
import os
import subprocess
import sys
import tempfile
import time

板 = os.path.join(os.path.dirname(os.path.abspath(__file__)), '板.py')
任 = '写作/长篇小说'   # 仓库自带的演示工作区里的任务（不设 BAN_ROOT 时看板读的就是它）


def 跑(记录, *参数):
    """记录：[(几秒前, {字段})]；返回 板.py 的输出"""
    with tempfile.TemporaryDirectory() as d:
        now = time.time()
        with open(os.path.join(d, '开关.jsonl'), 'w', encoding='utf-8') as f:
            for 前, e in 记录:
                f.write(json.dumps({'时间': now - 前, '任务': 任, '谁': 'Claude', '会话': 's1', **e}, ensure_ascii=False) + '\n')
        env = dict(os.environ, BAN_DATA=d)
        r = subprocess.run(['/usr/bin/python3', 板, *参数], capture_output=True, text=True, env=env, timeout=30)
        return r.stdout + r.stderr


def 开(预计, 说='上一段的事', **kw):
    return {'开': True, '预计': 预计, '说': 说, **kw}


收 = {'开': False, '等你': True}
开工 = ['开工', 任, '--会话', 's1', '--接入', 'claude']
错 = []


def 查(名, 出, 有=(), 无=()):
    缺 = [x for x in 有 if x not in 出] + [f'不该有：{x}' for x in 无 if x in 出]
    print(('✅ ' if not 缺 else '❌ ') + 名 + ('' if not 缺 else f'  缺 {缺}\n    输出：{出!r}'))
    if 缺:
        错.append(名)


查('上一段照预计做完：报实际和倍数，不提醒', 跑([(600, 开(10))], *开工, '--预计', '5'),
  有=['上一段「上一段的事」预计 10 分钟，实际 10 分钟（1 倍）'], 无=['⚠'])
查('不到四分之一：提醒补一句、重估', 跑([(60, 开(20))], *开工, '--预计', '5'), 有=['⚠ 不到预估的四分之一'])
查('0.2 倍（贴着四分之一的线）：也提醒', 跑([(120, 开(10))], *开工, '--预计', '5'), 有=['（0.2 倍）', '⚠ 不到预估的四分之一'])
查('超过两倍：提醒卡在哪', 跑([(1800, 开(10))], *开工, '--预计', '5'), 有=['⚠ 超过预估一倍'])
查('插件每轮开始的续期（不带预计）不算断', 跑([(1100, 开(10)), (900, 开(None, '「你说的话」'))], *开工, '--预计', '5'),
  有=['实际 18 分钟（1.8 倍）'], 无=['⚠'])
查('收工就断：按收工那一刻算', 跑([(1500, 开(10)), (900, 收)], *开工, '--预计', '5'), 有=['实际 10 分钟（1 倍）'])
查('一小时前就收了的上一段：不再报', 跑([(9000, 开(10)), (7200, 收)], *开工, '--预计', '5'), 无=['上一段'])
查('别的会话的段：不报', 跑([(600, 开(10, 会话='s2'))], *开工, '--预计', '5'), 无=['上一段'])
查('别的任务收工不断这一段', 跑([(1200, 开(10)), (900, {**收, '任务': '创作/示例小说'})], *开工, '--预计', '5'),
  有=['实际 20 分钟'])
查('往常：做完的段够 3 段就按中位数换算', 跑([(4000, 开(10)), (3700, 收), (3000, 开(10)), (2700, 收), (2000, 开(10)), (1700, 收)],
                                 *开工, '--预计', '10'),
  有=['最近 3 段实际是预计的 0.5–0.5 倍，中位 0.5', '按往常约 5.0 分钟'])
查('不到 3 段：说没法校准', 跑([(600, 开(10))], *开工, '--预计', '5'), 有=['还不到 3 段'])
查('不带预计的开工：不报、不校准', 跑([(600, 开(10))], *开工), 无=['上一段', '估时'])
查('自己敲收工：报这一段', 跑([(300, 开(10))], '收工', 任, '--会话', 's1'), 有=['这一段「上一段的事」预计 10 分钟，实际 5.0 分钟（0.5 倍）'])
查('12 小时没收工：不算', 跑([(13 * 3600, 开(10))], *开工, '--预计', '5'), 无=['上一段'])
查('对账：列每段、没收工的标不算、末尾汇总',
  跑([(14 * 3600, 开(10, '忘了收')), (4000, 开(10, '甲')), (3700, 收), (60, 开(20, '乙'))], '对账'),
  有=['「忘了收」  预计 10，12 小时没收工，不算', '「甲」  预计 10 → 实际 5.0  0.5 倍', '（还在做）', '做完的 1 段：中位 0.5 倍'])

print(f'\n{"全过" if not 错 else f"{len(错)} 条没过"}')
sys.exit(1 if 错 else 0)
